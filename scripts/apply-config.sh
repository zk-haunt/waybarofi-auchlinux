#!/usr/bin/env bash
# Script to safely apply/sync configurations from the repository to ~/.config

set -euo pipefail

REPO_CONFIG_DIR="$(cd "$(dirname "$0")/../config" && pwd)"
TARGET_DIR="$HOME/.config"

DRY_RUN=false
NO_BACKUP=false
ARGS=()
for arg in "$@"; do
  case "$arg" in
    -n|--dry-run) DRY_RUN=true ;;
    --no-backup)  NO_BACKUP=true ;;
    -h|--help)
      cat <<'EOT'
Usage: ./scripts/apply-config.sh [OPTIONS] [FOLDER...]

Deploys config/<folder> to ~/.config/<folder>. With no FOLDER arguments every
configured folder is synced.

Options:
  -n, --dry-run   Show what WOULD change and exit. Nothing is written, no
                  services are restarted, no backup is taken. Use this first.
  --no-backup     Skip the pre-sync snapshot. Only for a known-clean re-run.
  -h, --help      This text.

Folders are synced with `rsync --delete`, so anything in ~/.config/<folder>
that is not in the repo is DELETED. Runtime-generated files are protected by
RUNTIME_EXCLUDES below; a file that must survive belongs in that list.
EOT
      exit 0 ;;
    *) ARGS+=("$arg") ;;
  esac
done
set -- "${ARGS[@]+"${ARGS[@]}"}"

$DRY_RUN && echo "==== DRY RUN — nothing will be written ====" \
         || echo "==== Applying configurations from repository to ~/.config ===="

# Runtime state that must NEVER be deleted, applied to EVERY folder.
#
# This exists because the old per-folder exclude lists drifted: only zsh, rofi
# and waybar had any, so `rsync --delete` silently removed the starship theme
# symlink and the hypr .current selection files on every single run. A pattern
# here is checked against all folders, so a new folder cannot reintroduce that
# class of bug by omission.
#
# rsync matches a pattern with no slash against the BASENAME at any depth, and a
# pattern with a slash against the path relative to the folder root.
RUNTIME_EXCLUDES=(
  # Selection state written by the picker scripts
  --exclude=.current                  # hypr animations / hyprlock active preset
  --exclude=rofi_theme_mode           # rofi active theme
  --exclude=waybar_theme_mode         # waybar active theme
  # Symlinks created at runtime to point at the active variant
  --exclude=starship.toml             # -> starship_<theme>.toml
  --exclude=style.rasi                # -> style_<theme>.rasi
  # Generated by matugen from the wallpaper; the repo copy is a stale snapshot
  --exclude=colors-matugen.rasi
  --exclude=colors.css
  --exclude=color.conf
  --exclude=colors.lua
  --exclude=flavor.toml               # yazi's "auch" flavor (yazi/flavors/auch.yazi/)
  # Rewritten by hypr/scripts/swaync-buttons.sh every time the SwayNC panel opens
  --exclude=battery.css
  # Referenced by the waybar configs but not tracked in the repo
  --exclude=power_menu.xml
  # Caches and history
  --exclude=.zcompdump*
  --exclude=.zsh_history
  --exclude=.zsh_sessions/
)

# Folders to sync. rsync --delete: the destination is made to match the repo
# EXACTLY, so anything in ~/.config/<folder> that is not in the repo is
# DELETED — except what RUNTIME_EXCLUDES above protects.
FOLDERS=(
  "cava"
  "dunst"
  "fastfetch"
  "gtk-3.0"
  "gtk-4.0"
  "hypr"
  "kitty"
  "menus"
  "matugen"
  "nwg-look"
  "pypr"
  "Kvantum"
  "qt5ct"
  "qt6ct"
  "uwsm"
  "xsettingsd"
  "satty"
  "rofi"
  "starship"
  "swaync"
  "waybar"
  "xfce4"
  "yazi"
  "zsh"
)

# Folders to merge (will copy files recursively without wiping the target folder)
MERGE_FOLDERS=(
  "Code - OSS"
)

# Filter folders if arguments are provided
SELECTED_FOLDERS=()
if [[ $# -gt 0 ]]; then
  for arg in "$@"; do
    found=false
    for f in "${FOLDERS[@]}" "${MERGE_FOLDERS[@]}"; do
      if [[ "$arg" == "$f" ]]; then
        SELECTED_FOLDERS+=("$arg")
        found=true
        break
      fi
    done
    if [[ "$found" == false ]]; then
      echo "[Warning] Folder '$arg' is not configured for syncing. Skipping."
    fi
  done
  if [[ ${#SELECTED_FOLDERS[@]} -eq 0 ]]; then
    echo "[Error] No valid folders specified. Exiting."
    exit 1
  fi
else
  # Default to syncing all folders
  SELECTED_FOLDERS=("${FOLDERS[@]}" "${MERGE_FOLDERS[@]}")
fi

# Folder arguments mean "just these folders". The extras further down that
# belong to no folder — the single files (dolphinrc, kdeglobals, mimeapps.list),
# KeePassXC (killed with -9 so it can't write its ini back), Dolphin state,
# user units, cursor/GTK setup — run on a full sync only. They used to run on
# every call, so `apply-config.sh waybar` killed an open KeePassXC and lost
# any unsaved database change (found 2026-10-09).
FULL_SYNC=true
[[ $# -gt 0 ]] && FULL_SYNC=false

contains_folder() {
  local item="$1"
  for f in "${SELECTED_FOLDERS[@]}"; do
    if [[ "$f" == "$item" ]]; then
      return 0
    fi
  done
  return 1
}

# Snapshot every folder we are about to --delete into, BEFORE touching anything.
# The old header comment claimed a backup happened here; it never did, and
# scripts/backup-config.sh had zero callers. A --delete over a live ~/.config
# with no snapshot is how the starship theme symlink got lost.
#
# Cheap by design: tar of only the selected target dirs, pruned to the last 5.
# Skipped on --dry-run (nothing is written) and on --no-backup.
if ! $DRY_RUN && ! $NO_BACKUP; then
  BACKUP_ROOT="${XDG_CACHE_HOME:-$HOME/.cache}/apply-config-backups"
  BACKUP_TGZ="$BACKUP_ROOT/$(date +%Y-%m-%d_%H-%M-%S).tar.gz"
  mkdir -p "$BACKUP_ROOT"

  BACKUP_PATHS=()
  for folder in "${SELECTED_FOLDERS[@]}"; do
    # Merge folders are only ever added to, never --delete'd, so there is
    # nothing to protect — and "Code - OSS" is ~275M of editor cache, which
    # made a full-sync backup 170M instead of ~9M (seen 2026-10-09).
    for m in "${MERGE_FOLDERS[@]}"; do [[ $m == "$folder" ]] && continue 2; done
    [[ -d "$TARGET_DIR/$folder" ]] && BACKUP_PATHS+=("$folder")
  done

  if (( ${#BACKUP_PATHS[@]} )); then
    # Relative to $TARGET_DIR so a restore is an unambiguous tar -C ~/.config -xzf.
    if tar -czf "$BACKUP_TGZ" -C "$TARGET_DIR" "${BACKUP_PATHS[@]}" 2>/dev/null; then
      echo "[Backup] ${#BACKUP_PATHS[@]} folder(s) -> $BACKUP_TGZ ($(du -h "$BACKUP_TGZ" | cut -f1))"
      echo "[Backup] Restore with: tar -C \"$TARGET_DIR\" -xzf \"$BACKUP_TGZ\""
    else
      # Never let a backup failure silently become an unprotected --delete.
      echo "[Error] Backup failed — refusing to run a destructive sync." >&2
      echo "        Re-run with --no-backup if you genuinely want to skip it." >&2
      exit 1
    fi
    # Keep the 5 most recent.
    ls -1t "$BACKUP_ROOT"/*.tar.gz 2>/dev/null | tail -n +6 | while read -r old_bk; do
      rm -f "$old_bk"
    done
  fi
fi

# Sync each standard folder
for folder in "${FOLDERS[@]}"; do
  contains_folder "$folder" || continue
  SRC="$REPO_CONFIG_DIR/$folder"
  DST="$TARGET_DIR/$folder"
  
  if [ -d "$SRC" ]; then
    # If the destination is a file or symlink, remove it so rsync can write to the directory
    if [ -f "$DST" ] || [ -L "$DST" ]; then
      echo "[Clean] Removing file/symlink at $DST"
      rm -f "$DST"
    fi
    
    echo "[Sync] Syncing $folder to ~/.config/..."
    mkdir -p "$DST"
    # Start from the global runtime allowlist, then add folder-specific ones.
    RSYNC_EXCLUDES=("${RUNTIME_EXCLUDES[@]}")
    if [[ "$folder" == "zsh" ]]; then
      RSYNC_EXCLUDES+=("--exclude=ohmyzsh/")       # installed by term-n-font.sh
    elif [[ "$folder" == "waybar" ]]; then
      # These are symlinks INTO THE GIT WORKTREE (-> config/waybar/themes/...),
      # created by the waybar-theme switcher. Excluding them is load-bearing:
      # without it --delete removes the symlink and the bar loses its theme.
      # Consequence worth knowing: a `git stash` or branch switch restyles the
      # live bar instantly, because the live files ARE the repo files.
      RSYNC_EXCLUDES+=("--exclude=modules/")
      RSYNC_EXCLUDES+=("--exclude=includes/")
      RSYNC_EXCLUDES+=("--exclude=theme.css")
      RSYNC_EXCLUDES+=("--exclude=config.jsonc")
      RSYNC_EXCLUDES+=("--exclude=style.css")
    fi

    if $DRY_RUN; then
      out="$(rsync --archive --delete --dry-run -i "${RSYNC_EXCLUDES[@]}" "$SRC/" "$DST/")"
      dels="$(printf '%s\n' "$out" | grep -E '^\*deleting' || true)"
      ndel=$(printf '%s' "$dels" | grep -c . || true)
      nchg=$(printf '%s\n' "$out" | grep -cE '^[<>ch]' || true)
      echo "[DRY] $folder: $nchg to write, $ndel to DELETE"
      [[ -n "$dels" ]] && printf '%s\n' "$dels" | sed 's/^\*deleting *//; s|^|        DELETE |'
    else
      rsync --archive --delete "${RSYNC_EXCLUDES[@]}" "$SRC/" "$DST/"
    fi
  else
    echo "[Skip] Folder $folder does not exist in repository config."
  fi
done

# Merge each merge-folder
for folder in "${MERGE_FOLDERS[@]}"; do
  contains_folder "$folder" || continue
  SRC="$REPO_CONFIG_DIR/$folder"
  DST="$TARGET_DIR/$folder"
  
  if [ -d "$SRC" ]; then
    if $DRY_RUN; then
      # No --delete here, so a merge can only add/overwrite, never remove.
      n=$(rsync --archive --dry-run -i "$SRC/" "$DST/" 2>/dev/null | grep -cE '^[<>ch]' || true)
      echo "[DRY] $folder (merge): ${n:-0} file(s) would be written, 0 deleted"
    else
      echo "[Sync-Merge] Merging $folder into ~/.config/..."
      mkdir -p "$DST"
      rsync --archive "$SRC/" "$DST/"
    fi
  else
    echo "[Skip] Merge folder $folder does not exist in repository config."
  fi
done

# systemd --user units.
#
# NOT added to FOLDERS: that path runs `rsync --delete`, which would wipe any
# other user unit you have ever installed by hand. These are copied in
# additively instead, and a stale unit is removed by deleting it here and from
# ~/.config/systemd/user explicitly.
if $FULL_SYNC && [[ -d "$REPO_CONFIG_DIR/systemd/user" ]]; then
  if $DRY_RUN; then
    echo "[DRY] would install systemd --user units + daemon-reload"
  else
    echo "[Sync] Installing systemd --user units..."
    mkdir -p "$TARGET_DIR/systemd/user"
    rsync --archive "$REPO_CONFIG_DIR/systemd/user/" "$TARGET_DIR/systemd/user/"
    systemctl --user daemon-reload 2>/dev/null || true
    # Enable anything shipped with an [Install] section. Idempotent; a unit that
    # is already enabled is a no-op.
    for _unit in "$REPO_CONFIG_DIR"/systemd/user/*.service; do
      [[ -f "$_unit" ]] || continue
      grep -q '^\[Install\]' "$_unit" || continue
      _name="$(basename "$_unit")"
      systemctl --user enable "$_name" >/dev/null 2>&1 \
        && echo "[Sync]   enabled $_name" \
        || echo "[Warn]   could not enable $_name"
    done
    # Timers are enabled AND started: a timer that is only enabled stays idle
    # until the next login. The service a timer drives has no [Install] section,
    # so the loop above rightly skips it.
    for _unit in "$REPO_CONFIG_DIR"/systemd/user/*.timer; do
      [[ -f "$_unit" ]] || continue
      _name="$(basename "$_unit")"
      systemctl --user enable --now "$_name" >/dev/null 2>&1 \
        && echo "[Sync]   enabled + started $_name" \
        || echo "[Warn]   could not enable $_name"
    done
  fi
fi

# Generated-but-REQUIRED files. matugen rewrites these from the wallpaper at
# runtime, so they live in RUNTIME_EXCLUDES to stop --delete clobbering the live
# palette with the repo's stale snapshot. But they are also required at parse
# time — anim.lua does require("hyprland/colors"), the waybar themes @import
# colors.css, kitty.conf includes color.conf — so a fresh install with no copy
# at all would fail to start Hyprland entirely.
#
# Hence: seed them ONLY when the target is missing. Never overwrite, so the live
# matugen output always wins on an existing install.
GENERATED_SEEDS=(
  "hypr/hyprland/colors.lua"
  "waybar/colors.css"
  "kitty/color.conf"
  "rofi/colors/colors-matugen.rasi"
  "yazi/flavors/auch.yazi/flavor.toml"   # theme.toml names this flavor; without it yazi silently uses its default colours
  "swaync/colors.css"                    # the "matugen" SwayNC theme @imports it; without it the panel loses every colour
)
for rel in "${GENERATED_SEEDS[@]}"; do
  src="$REPO_CONFIG_DIR/$rel"
  dst="$TARGET_DIR/$rel"
  [[ -f "$src" ]] || continue
  if [[ ! -f "$dst" ]]; then
    if $DRY_RUN; then
      echo "[DRY] would SEED missing $rel"
    else
      mkdir -p "$(dirname "$dst")"
      cp "$src" "$dst"
      echo "[Seed] $rel was missing — seeded from repo (matugen overwrites it on the next wallpaper change)"
    fi
  fi
done

# Everything past this point writes files outside the synced folders and
# restarts live services (waybar, swaync, keepassxc, hyprctl reload, gsettings,
# theme tarball extraction). A dry run must not do any of it, so stop here.
if $DRY_RUN; then
  echo
  echo "==== DRY RUN complete — nothing was written ===="
  if $FULL_SYNC; then
    echo "Not shown/performed in a dry run: individual file copies (dolphinrc,"
    echo "kdeglobals, mimeapps.list), the VPN module deploy, keepassxc restart,"
    echo "ksycoca rebuild, chmod sweep, hyprctl reload, waybar/swaync restarts,"
    echo "gsettings cursor sync, and icon/theme tarball extraction."
  else
    echo "Partial sync (${SELECTED_FOLDERS[*]}): only those folders, plus the chmod"
    echo "sweep, hyprctl reload and waybar/swaync restarts — and the VPN module"
    echo "deploy if waybar is among them. No single files, keepassxc or theme setup."
  fi
  echo "Re-run without --dry-run to apply."
  exit 0
fi

# Waybar VPN module script.
# Kept in scripts/vpn/ with its docs rather than config/waybar/scripts/, but
# waybar loads it from ~/.config/waybar/scripts/ — and the waybar sync above
# runs with --delete, so this MUST come after it or the deployed copy is
# removed on every run. Hence: whenever waybar was synced, full run or not.
if contains_folder "waybar" && [ -f "$REPO_CONFIG_DIR/../scripts/vpn/vpn.sh" ]; then
  echo "[Sync] Deploying VPN waybar module script..."
  mkdir -p "$TARGET_DIR/waybar/scripts"
  cp -f "$REPO_CONFIG_DIR/../scripts/vpn/vpn.sh" "$TARGET_DIR/waybar/scripts/vpn.sh"
  chmod +x "$TARGET_DIR/waybar/scripts/vpn.sh"
fi

# Full sync only from here to the ksycoca rebuild — see FULL_SYNC at the top.
if $FULL_SYNC; then
  # Sync individual files (like dolphinrc, kdeglobals)
  FILES=(
    "dolphinrc"
    "kdeglobals"
    "dolphinstaterc"
    "mimeapps.list"
  )

  for file in "${FILES[@]}"; do
    if [ -f "$REPO_CONFIG_DIR/$file" ]; then
      echo "[Sync] Syncing file $file to ~/.config/..."
      cp -f "$REPO_CONFIG_DIR/$file" "$TARGET_DIR/$file"
    fi
  done

  # Sync keepassxc config (lives in its own subdir).
  # KeePassXC rewrites its ini on exit, so a running instance would clobber what we
  # deploy. Kill it first (-9, so it can't write back), copy the config, then
  # relaunch — this makes the dark theme (GUI/ApplicationTheme=dark) actually apply.
  if [ -f "$REPO_CONFIG_DIR/keepassxc/keepassxc.ini" ]; then
    echo "[Sync] Syncing keepassxc config..."
    kp_was_running=false
    if pgrep -x keepassxc >/dev/null; then
      kp_was_running=true
      pkill -9 -x keepassxc 2>/dev/null
      sleep 1
    fi
    mkdir -p "$TARGET_DIR/keepassxc"
    cp -f "$REPO_CONFIG_DIR/keepassxc/keepassxc.ini" "$TARGET_DIR/keepassxc/keepassxc.ini"
    if [ "$kp_was_running" = true ]; then
      echo "[Reload] Restarting keepassxc to apply theme..."
      (keepassxc >/dev/null 2>&1 &)
    fi
  fi

  if [ -f "$REPO_CONFIG_DIR/dolphinstaterc" ]; then
    mkdir -p "$HOME/.local/state"
    cp -f "$REPO_CONFIG_DIR/dolphinstaterc" "$HOME/.local/state/dolphinstaterc"
  fi

  if [ -f "$REPO_CONFIG_DIR/dolphin_kxmlgui/dolphinui.rc" ]; then
    echo "[Sync] Syncing Dolphin UI layout to ~/.local/share/kxmlgui5/dolphin/..."
    mkdir -p "$HOME/.local/share/kxmlgui5/dolphin"
    cp -f "$REPO_CONFIG_DIR/dolphin_kxmlgui/dolphinui.rc" "$HOME/.local/share/kxmlgui5/dolphin/dolphinui.rc"
  fi

  if [ -f "$REPO_CONFIG_DIR/dolphin_global_dir" ]; then
    echo "[Sync] Syncing Dolphin global sorting layout..."
    mkdir -p "$HOME/.local/share/dolphin/view_properties/global"
    cp -f "$REPO_CONFIG_DIR/dolphin_global_dir" "$HOME/.local/share/dolphin/view_properties/global/.directory"
  fi
fi

# Rebuild the KDE application cache (ksycoca).
# uwsm exports XDG_MENU_PREFIX=hyprland-, so kbuildsycoca6 needs
# ~/.config/menus/hyprland-applications.menu (synced above) to exist —
# without it the cache is built with ZERO applications and Dolphin/KIO
# cannot open files with their default apps (imv, mpv, ark, ...).
# Needed after a full sync, or whenever menus/ itself was synced.
if { $FULL_SYNC || contains_folder "menus"; } && command -v kbuildsycoca6 >/dev/null 2>&1; then
  echo "[KDE] Rebuilding application cache (ksycoca)..."
  kbuildsycoca6 --noincremental >/dev/null 2>&1 || true
fi

# Ensure all scripts under ~/.config/ are executable
echo "[Permissions] Ensuring all scripts under ~/.config/ are executable..."
find "$TARGET_DIR" -type f \( -name "*.sh" -o -name "*.py" \) -exec chmod +x {} + 2>/dev/null || true

# Reload Hyprland config (if running)
if pgrep -x "Hyprland" > /dev/null; then
  echo "[Reload] Reloading Hyprland configuration..."
  hyprctl reload || true
  
  # Also reload waybar if running
  if systemctl --user is-active waybar.service >/dev/null 2>&1; then
    echo "[Reload] Restarting Waybar via systemd..."
    systemctl --user restart waybar || true
  elif pgrep -u "$USER" -x "waybar" > /dev/null; then
    echo "[Reload] Restarting Waybar manually..."
    # Was: pkill -USR2 waybar || pkill waybar && waybar &
    # Bash parses that as (A || B) && C, so a SUCCESSFUL USR2 signal still fell
    # through to `waybar &` and spawned a second bar on top of the live one.
    # Braces make the grouping explicit: only respawn if signalling failed.
    if ! pkill -u "$USER" -USR2 waybar 2>/dev/null; then
      pkill -u "$USER" waybar 2>/dev/null || true
      waybar >/dev/null 2>&1 &
    fi
  fi
  
  # Restart notification daemon
  if command -v swaync >/dev/null 2>&1; then
    echo "[Reload] Restarting SwayNC notification daemon..."
    systemctl --user restart swaync || (pkill -x swaync || true && swaync &)
  else
    echo "[Reload] Restarting Dunst notification daemon..."
    systemctl --user restart dunst || systemctl --user start dunst || true
  fi
fi

# Cursor, icon and GTK theme setup — full sync only (see FULL_SYNC at the top).
if ! $FULL_SYNC; then
  echo "==== Applied: ${SELECTED_FOLDERS[*]} (partial sync — theme setup skipped) ===="
  exit 0
fi

# Sync GTK Settings to dconf/gsettings
echo "[GTK] Syncing cursor theme to GSettings database..."
gsettings set org.gnome.desktop.interface cursor-theme "Bibata-Modern-Ice" || true
gsettings set org.gnome.desktop.interface cursor-size 24 || true
gsettings set org.gnome.desktop.interface color-scheme "prefer-dark" || true

echo "[GTK] Configuring fallback cursor in ~/.icons/default..."
mkdir -p "$HOME/.icons/default"
echo -e "[Icon Theme]\nInherits=Bibata-Modern-Ice" > "$HOME/.icons/default/index.theme"

# Extract offline cursor/icon themes to ~/.icons (only if not already extracted)
REPO_ICONS="$REPO_CONFIG_DIR/../scripts/icons"
if [ -d "$REPO_ICONS" ]; then
  mkdir -p "$HOME/.icons"
  for tarball in "$REPO_ICONS"/*.tar.gz; do
    [ -f "$tarball" ] || continue
    name=$(basename "$tarball" .tar.gz)
    if [ ! -d "$HOME/.icons/$name" ]; then
      echo "[Sync] Extracting cursor/icon theme $name to ~/.icons..."
      tar -xzf "$tarball" -C "$HOME/.icons/"
    fi
  done
fi

# Extract offline GTK themes to ~/.themes (only if not already extracted)
REPO_GTK_THEMES="$REPO_CONFIG_DIR/../scripts/gtk-themes"
if [ -d "$REPO_GTK_THEMES" ]; then
  mkdir -p "$HOME/.themes"
  for tarball in "$REPO_GTK_THEMES"/*.tar.gz; do
    [ -f "$tarball" ] || continue
    # NOTE: `| head -1` here would kill this script. head closes the pipe after
    # one line, tar dies of SIGPIPE (141), `set -o pipefail` propagates that, and
    # `set -e` aborts — silently, right before the success message, taking any
    # caller (term-n-font.sh) down with it. awk reads the whole listing instead.
    theme_dir=$(tar -tzf "$tarball" | awk -F/ 'NR==1{print $1}')
    if [ -n "$theme_dir" ] && [ ! -d "$HOME/.themes/$theme_dir" ]; then
      echo "[Sync] Extracting GTK theme $theme_dir to ~/.themes..."
      tar -xzf "$tarball" -C "$HOME/.themes/"
    fi
  done
fi

echo "==== Configurations successfully applied! ===="
